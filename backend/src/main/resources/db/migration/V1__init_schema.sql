-- V1__init_schema.sql
-- SentinelDesk AI Schema Definition

-- 1. USERS
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    role VARCHAR(50) NOT NULL,
    department VARCHAR(100),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_users_role ON users(role);
CREATE INDEX idx_users_email ON users(email);

-- 2. TEAMS
CREATE TABLE teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    category_focus VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. TEAM MEMBERSHIPS
CREATE TABLE team_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    is_team_lead BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_team_members_team FOREIGN KEY (team_id) REFERENCES teams(id) ON DELETE CASCADE,
    CONSTRAINT fk_team_members_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uk_team_user UNIQUE (team_id, user_id)
);

-- 4. SLA POLICIES
CREATE TABLE sla_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    priority VARCHAR(10) NOT NULL UNIQUE, -- P1, P2, P3, P4
    first_response_hours NUMERIC(6, 2) NOT NULL,
    resolution_hours NUMERIC(6, 2) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. INCIDENTS (Shared incidents grouping multiple tickets)
CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_number VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    severity VARCHAR(20) NOT NULL, -- CRITICAL, HIGH, MEDIUM, LOW
    status VARCHAR(30) NOT NULL, -- INVESTIGATING, IDENTIFIED, MONITORING, RESOLVED
    affected_service VARCHAR(100) NOT NULL,
    owner_id BIGINT,
    root_cause TEXT,
    resolution_summary TEXT,
    post_incident_review TEXT,
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_incident_owner FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_incidents_status ON incidents(status);
CREATE INDEX idx_incidents_severity ON incidents(severity);

-- 6. TICKETS
CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_number VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    requester_id BIGINT NOT NULL,
    assigned_agent_id BIGINT,
    assigned_team_id BIGINT,
    category VARCHAR(50) NOT NULL, -- SOFTWARE, HARDWARE, NETWORK, ACCESS, SECURITY, OUTAGE, OTHER
    priority VARCHAR(10) NOT NULL, -- P1, P2, P3, P4
    status VARCHAR(30) NOT NULL, -- NEW, TRIAGED, OPEN, IN_PROGRESS, PENDING_REQUESTER, RESOLVED, CLOSED, CANCELLED
    source VARCHAR(30) NOT NULL DEFAULT 'WEB',
    first_response_at TIMESTAMP,
    resolved_at TIMESTAMP,
    closed_at TIMESTAMP,
    sla_deadline TIMESTAMP,
    resolution_summary TEXT,
    related_incident_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ticket_requester FOREIGN KEY (requester_id) REFERENCES users(id),
    CONSTRAINT fk_ticket_agent FOREIGN KEY (assigned_agent_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_ticket_team FOREIGN KEY (assigned_team_id) REFERENCES teams(id) ON DELETE SET NULL,
    CONSTRAINT fk_ticket_incident FOREIGN KEY (related_incident_id) REFERENCES incidents(id) ON DELETE SET NULL
);

CREATE INDEX idx_tickets_requester ON tickets(requester_id);
CREATE INDEX idx_tickets_agent ON tickets(assigned_agent_id);
CREATE INDEX idx_tickets_team ON tickets(assigned_team_id);
CREATE INDEX idx_tickets_status ON tickets(status);
CREATE INDEX idx_tickets_priority ON tickets(priority);
CREATE INDEX idx_tickets_sla_deadline ON tickets(sla_deadline);
CREATE INDEX idx_tickets_created_at ON tickets(created_at);

-- 7. INCIDENT TICKET ASSOCIATIONS
CREATE TABLE incident_tickets (
    incident_id BIGINT NOT NULL,
    ticket_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (incident_id, ticket_id),
    CONSTRAINT fk_inc_ticket_incident FOREIGN KEY (incident_id) REFERENCES incidents(id) ON DELETE CASCADE,
    CONSTRAINT fk_inc_ticket_ticket FOREIGN KEY (ticket_id) REFERENCES tickets(id) ON DELETE CASCADE
);

-- 8. TICKET COMMENTS (Public replies & private internal notes)
CREATE TABLE ticket_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    content TEXT NOT NULL,
    is_internal BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comment_ticket FOREIGN KEY (ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
    CONSTRAINT fk_comment_author FOREIGN KEY (author_id) REFERENCES users(id)
);

CREATE INDEX idx_comments_ticket ON ticket_comments(ticket_id);

-- 9. TICKET STATUS HISTORY
CREATE TABLE ticket_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL,
    changed_by_id BIGINT,
    old_status VARCHAR(30),
    new_status VARCHAR(30) NOT NULL,
    reason TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_status_hist_ticket FOREIGN KEY (ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
    CONSTRAINT fk_status_hist_user FOREIGN KEY (changed_by_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_status_hist_ticket ON ticket_status_history(ticket_id);

-- 10. TICKET ASSIGNMENT HISTORY
CREATE TABLE ticket_assignment_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL,
    changed_by_id BIGINT,
    old_agent_id BIGINT,
    new_agent_id BIGINT,
    old_team_id BIGINT,
    new_team_id BIGINT,
    reason TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assign_hist_ticket FOREIGN KEY (ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
    CONSTRAINT fk_assign_hist_actor FOREIGN KEY (changed_by_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_assign_hist_ticket ON ticket_assignment_history(ticket_id);

-- 11. TICKET AI SUGGESTIONS
CREATE TABLE ticket_ai_suggestions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL,
    suggested_category VARCHAR(50),
    suggested_priority VARCHAR(10),
    summary TEXT,
    suggested_domain VARCHAR(100),
    suggested_team VARCHAR(100),
    diagnostic_questions_json TEXT,
    suggested_actions_json TEXT,
    priority_explanation TEXT,
    confidence_estimate NUMERIC(5, 2),
    model_provider VARCHAR(50),
    model_name VARCHAR(100),
    is_accepted BOOLEAN DEFAULT FALSE,
    is_overridden BOOLEAN DEFAULT FALSE,
    human_override_reason TEXT,
    overridden_by_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ai_sugg_ticket FOREIGN KEY (ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
    CONSTRAINT fk_ai_sugg_overridden_by FOREIGN KEY (overridden_by_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_ai_sugg_ticket ON ticket_ai_suggestions(ticket_id);

-- 12. SLA TRACKING RECORDS
CREATE TABLE sla_trackers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL UNIQUE,
    policy_id BIGINT NOT NULL,
    first_response_deadline TIMESTAMP NOT NULL,
    first_response_met BOOLEAN DEFAULT FALSE,
    first_response_breached BOOLEAN DEFAULT FALSE,
    resolution_deadline TIMESTAMP NOT NULL,
    resolution_met BOOLEAN DEFAULT FALSE,
    resolution_breached BOOLEAN DEFAULT FALSE,
    is_escalated BOOLEAN DEFAULT FALSE,
    warning_issued BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sla_ticket FOREIGN KEY (ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
    CONSTRAINT fk_sla_policy FOREIGN KEY (policy_id) REFERENCES sla_policies(id)
);

CREATE INDEX idx_sla_res_deadline ON sla_trackers(resolution_deadline);
CREATE INDEX idx_sla_breached ON sla_trackers(resolution_breached);

-- 13. ESCALATION EVENTS
CREATE TABLE escalation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL,
    tracker_id BIGINT NOT NULL,
    escalation_level VARCHAR(30) NOT NULL, -- WARNING_80, FIRST_RESPONSE_BREACH, RESOLUTION_BREACH
    reason TEXT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'TRIGGERED', -- TRIGGERED, ACKNOWLEDGED, RESOLVED
    escalated_to_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP,
    CONSTRAINT fk_esc_ticket FOREIGN KEY (ticket_id) REFERENCES tickets(id) ON DELETE CASCADE,
    CONSTRAINT fk_esc_tracker FOREIGN KEY (tracker_id) REFERENCES sla_trackers(id) ON DELETE CASCADE,
    CONSTRAINT fk_esc_to_user FOREIGN KEY (escalated_to_id) REFERENCES users(id) ON DELETE SET NULL,
    -- Prevent duplicate escalation events for same ticket and condition
    CONSTRAINT uk_ticket_escalation_level UNIQUE (ticket_id, escalation_level)
);

CREATE INDEX idx_esc_ticket ON escalation_events(ticket_id);
CREATE INDEX idx_esc_status ON escalation_events(status);

-- 14. NOTIFICATIONS
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL,
    title VARCHAR(150) NOT NULL,
    message TEXT NOT NULL,
    link VARCHAR(255),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notif_recipient FOREIGN KEY (recipient_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_notif_recipient_read ON notifications(recipient_id, is_read);

-- 15. AUDIT LOGS
CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(50) NOT NULL,
    entity_id VARCHAR(50),
    details TEXT,
    ip_address VARCHAR(45),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_audit_entity ON audit_logs(entity_type, entity_id);
CREATE INDEX idx_audit_user ON audit_logs(user_id);
